async function analyzeDataInsights(
  file: any,
  duckDBState: any
): Promise<DataInsight[]> {
  const insights: DataInsight[] = [];

  if (!file.data || !file.columnTypes) return insights;

  const data = file.data;
  const schema = file.columnTypes;
  const tableName = file.tableName;

  // Handle different schema formats safely
  const getColumnInfo = (col: any, index: number) => {
    if (col && typeof col === "object" && col.name) {
      return { name: col.name, type: col.type };
    }

    if (data.length > 0) {
      const dataKeys = Object.keys(data[0]);
      const name = dataKeys[index];
      return { name, type: col };
    }

    return null;
  };

  const columnInfo = schema
    .map((col: any, index: number) => getColumnInfo(col, index))
    .filter(Boolean);

  if (columnInfo.length === 0) return insights;

  // Data Quality Analysis
  const nullCounts = columnInfo
    .map((col) => {
      const nullCount = data.filter(
        (row) => row[col.name] == null || row[col.name] === ""
      ).length;
      return {
        column: col.name,
        nulls: nullCount,
        percentage: (nullCount / data.length) * 100,
      };
    })
    .filter((item) => item.percentage > 5);

  if (nullCounts.length > 0) {
    insights.push({
      id: `quality-missing-${file.id}`,
      type: "quality",
      title: "Missing Data Detected",
      description: `${
        nullCounts.length
      } columns have >5% missing values: ${nullCounts
        .map((c) => c.column)
        .join(", ")}`,
      severity: nullCounts.some((c) => c.percentage > 25) ? "warning" : "info",
      suggestedAction: "Consider data cleaning or filtering before analysis",
      confidence: 0.9,
      fileId: file.id,
      tableName,
      timestamp: Date.now(),
    });
  }

  // Dataset Size Analysis
  if (data.length > 50000) {
    insights.push({
      id: `performance-large-${file.id}`,
      type: "performance",
      title: "Large Dataset",
      description: `${data.length.toLocaleString()} rows detected - consider sampling for visualization`,
      severity: "info",
      suggestedAction: "Use LIMIT clause or sampling for better performance",
      confidence: 0.8,
      fileId: file.id,
      tableName,
      timestamp: Date.now(),
    });
  }

  // Duplicate Detection (sample-based for performance)
  const sampleSize = Math.min(1000, data.length);
  const sample = data.slice(0, sampleSize);
  const uniqueRows = new Set(sample.map((row) => JSON.stringify(row))).size;
  const duplicatePercentage = ((sampleSize - uniqueRows) / sampleSize) * 100;

  if (duplicatePercentage > 10) {
    insights.push({
      id: `quality-duplicates-${file.id}`,
      type: "quality",
      title: "Potential Duplicates",
      description: `~${Math.round(
        duplicatePercentage
      )}% duplicate rows detected in sample`,
      severity: duplicatePercentage > 25 ? "warning" : "info",
      suggestedAction: "Consider deduplication before analysis",
      confidence: 0.7,
      fileId: file.id,
      tableName,
      timestamp: Date.now(),
    });
  }

  return insights;
}

async function generateChartSuggestions(
  file: any,
  duckDBState: any
): Promise<ChartSuggestion[]> {
  const suggestions: ChartSuggestion[] = [];

  if (!file.data || !file.columnTypes) return suggestions;

  const data = file.data;
  const schema = file.columnTypes;
  const tableName = file.tableName;

  // Handle different schema formats safely
  const getColumnInfo = (col: any, index: number) => {
    if (col && typeof col === "object" && col.name) {
      return { name: col.name, type: col.type };
    }

    if (data.length > 0) {
      const dataKeys = Object.keys(data[0]);
      const name = dataKeys[index];
      return { name, type: col };
    }

    return null;
  };

  const columnInfo = schema
    .map((col: any, index: number) => getColumnInfo(col, index))
    .filter(Boolean);

  if (columnInfo.length === 0) return suggestions;

  // Get column types - handle both string types and ColumnType enums
  const numericColumns = columnInfo
    .filter(
      (col) => col.type === "number" || col.type === "Number" || col.type === 1 // ColumnType.Number = 1
    )
    .map((col) => col.name);

  const categoricalColumns = columnInfo
    .filter(
      (col) => col.type === "string" || col.type === "String" || col.type === 0 // ColumnType.String = 0
    )
    .map((col) => col.name);

  const dateColumns = columnInfo
    .filter((col) => {
      const name = col.name ? col.name.toLowerCase() : "";
      return (
        name.includes("date") ||
        name.includes("time") ||
        col.type === "date" ||
        col.type === "Date" ||
        col.type === 2
      ); // ColumnType.Date = 2
    })
    .map((col) => col.name);

  // Time Series Detection
  if (dateColumns.length > 0 && numericColumns.length > 0) {
    suggestions.push({
      id: `time-series-${file.id}`,
      type: "line",
      title: "Time Series Trend",
      description: `Track ${numericColumns[0]} over time`,
      confidence: 0.9,
      xAxis: dateColumns[0],
      yAxis: numericColumns[0],
      reasoning:
        "Date column detected with numeric data - perfect for trend analysis",
      fileId: file.id,
      tableName,
      sampleQuery: `SELECT "${dateColumns[0]}", "${numericColumns[0]}" FROM "${tableName}" ORDER BY "${dateColumns[0]}" LIMIT 100`,
    });
  }

  // Category Distribution
  if (categoricalColumns.length > 0 && numericColumns.length > 0) {
    // Check cardinality of categorical column
    const sampleData = data.slice(0, 1000);
    const uniqueValues = new Set(
      sampleData.map((row) => row[categoricalColumns[0]])
    ).size;

    if (uniqueValues <= 20) {
      // Good for bar chart
      suggestions.push({
        id: `category-bar-${file.id}`,
        type: "bar",
        title: "Category Comparison",
        description: `Compare ${numericColumns[0]} across ${categoricalColumns[0]}`,
        confidence: 0.85,
        xAxis: categoricalColumns[0],
        yAxis: numericColumns[0],
        reasoning: `Found ${uniqueValues} categories - ideal for comparison`,
        fileId: file.id,
        tableName,
        sampleQuery: `SELECT "${categoricalColumns[0]}", AVG("${numericColumns[0]}") as avg_value FROM "${tableName}" GROUP BY "${categoricalColumns[0]}" LIMIT 20`,
      });
    }

    if (uniqueValues <= 8) {
      // Good for pie chart
      suggestions.push({
        id: `category-pie-${file.id}`,
        type: "pie",
        title: "Distribution Breakdown",
        description: `Show distribution of ${categoricalColumns[0]}`,
        confidence: 0.8,
        xAxis: categoricalColumns[0],
        yAxis: "count",
        reasoning: `${uniqueValues} categories perfect for pie chart`,
        fileId: file.id,
        tableName,
        sampleQuery: `SELECT "${categoricalColumns[0]}", COUNT(*) as count FROM "${tableName}" GROUP BY "${categoricalColumns[0]}"`,
      });
    }
  }

  // Correlation Analysis
  if (numericColumns.length >= 2) {
    suggestions.push({
      id: `correlation-scatter-${file.id}`,
      type: "scatter",
      title: "Correlation Analysis",
      description: `Explore relationship between ${numericColumns[0]} and ${numericColumns[1]}`,
      confidence: 0.75,
      xAxis: numericColumns[0],
      yAxis: numericColumns[1],
      colorBy:
        categoricalColumns.length > 0 ? categoricalColumns[0] : undefined,
      reasoning: "Multiple numeric columns - good for correlation analysis",
      fileId: file.id,
      tableName,
      sampleQuery: `SELECT "${numericColumns[0]}", "${numericColumns[1]}"${
        categoricalColumns.length > 0 ? `, "${categoricalColumns[0]}"` : ""
      } FROM "${tableName}" LIMIT 500`,
    });
  }

  return suggestions;
}

