async function generateBasicSQL(
  intentResult: IntentResult,
  fileContext: any
): Promise<string> {
  if (!fileContext?.tableName) {
    throw new Error("No table context available");
  }

  const { intent, entities, parameters } = intentResult;
  const tableName = `"${fileContext.tableName}"`;

  switch (intent) {
    case "show_data":
      const columns =
        entities.columns.length > 0
          ? entities.columns.map((col) => `"${col}"`).join(", ")
          : "*";
      return `SELECT ${columns} FROM ${tableName} LIMIT 100`;

    case "filter_data":
      const filterCol = parameters.filterColumn
        ? `"${parameters.filterColumn}"`
        : '"*"';
      const filterVal = parameters.filterValue || "value";
      return `SELECT * FROM ${tableName} WHERE ${filterCol} = '${filterVal}' LIMIT 100`;

    case "aggregate_data":
      const aggCol = parameters.groupBy
        ? `"${parameters.groupBy}"`
        : entities.columns[0]
        ? `"${entities.columns[0]}"`
        : "column1";
      const agg = parameters.aggregation || "COUNT";
      return `SELECT ${aggCol}, ${agg}(*) as ${agg.toLowerCase()}_value FROM ${tableName} GROUP BY ${aggCol} LIMIT 50`;

    case "sort_data":
      const sortCol = entities.columns[0]
        ? `"${entities.columns[0]}"`
        : "column1";
      return `SELECT * FROM ${tableName} ORDER BY ${sortCol} DESC LIMIT 100`;

    default:
      return `SELECT * FROM ${tableName} LIMIT 10`;
  }
}

